// Copies the WhosRight ABI from the Foundry build into the app as a typed `as const` export.
// Usage: (cd contracts && forge build) && node scripts/sync-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = resolve(root, "../contracts/out/WhosRight.sol/WhosRight.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const out = resolve(root, "src/lib/abi/whosRight.ts");
writeFileSync(
  out,
  `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit by hand.\nexport const whosRightAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${abi.length} ABI entries to ${out}`);
